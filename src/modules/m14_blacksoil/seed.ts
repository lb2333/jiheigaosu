export async function seedM14(dbInstance = db) {
  for (const parcel of INITIAL_BLACKSOIL_PARCELS) {
    await dbInstance
      .insert(blacksoilParcels)
      .values(parcel)
      .onConflictDoUpdate({
        target: blacksoilParcels.id,
        set: {
          name: parcel.name,
          sectionId: parcel.sectionId,
          sectionName: parcel.sectionName,
          scope: parcel.scope,
          stake: parcel.stake,
          landType: parcel.landType,
          protectionLayer: parcel.protectionLayer,
          grade: parcel.grade,
          areaHa: parcel.areaHa,
          relation: parcel.relation,
          topsoilStatus: parcel.topsoilStatus,
          topsoilThicknessCm: parcel.topsoilThicknessCm,
          topsoilCompliant: parcel.topsoilCompliant,
          complianceStatus: parcel.complianceStatus,
          reviewNote: parcel.reviewNote,
          reviewedBy: parcel.reviewedBy,
          reviewedAt: parcel.reviewedAt,
          stripVol: parcel.stripVol,
          backfillPlan: parcel.backfillPlan,
          ndviSeries: parcel.ndviSeries,
          moistureSeries: parcel.moistureSeries,
          epochNotes: parcel.epochNotes,
          polygonPoints: parcel.polygonPoints,
          centerPoint: parcel.centerPoint,
          labelOffset: parcel.labelOffset,
          focusZoom: parcel.focusZoom,
          sortOrder: parcel.sortOrder,
        },
      });
  }
}
