function makeParcel(
  input: Omit<typeof blacksoilParcels.$inferInsert, 'centerPoint' | 'updatedAt'>
): typeof blacksoilParcels.$inferInsert {
  const centerPoint: BlacksoilPoint2D = computePolygonCenter(input.polygonPoints);
  return {
    ...input,
    centerPoint,
  };
}

