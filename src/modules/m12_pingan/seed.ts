export async function seedM12(dbInstance = db) {
  for (const item of SHOWCASE_ITEMS) {
    await dbInstance
      .insert(pinganShowcaseItems)
      .values(item)
      .onConflictDoUpdate({
        target: pinganShowcaseItems.id,
        set: {
          itemType: item.itemType,
          title: item.title,
          subtitle: item.subtitle,
          summary: item.summary,
          topicId: item.topicId,
          topicLabel: item.topicLabel,
          kind: item.kind,
          imgPath: item.imgPath,
          stake: item.stake,
          durationSec: item.durationSec,
          durationStr: item.durationStr,
          category: item.category,
          author: item.author,
          publishDate: item.publishDate,
          payload: item.payload,
          sortOrder: item.sortOrder,
          updatedAt: new Date(),
        },
      });
  }

  await dbInstance
    .insert(pinganTopics)
    .values(INITIAL_TOPICS)
    .onConflictDoNothing({ target: pinganTopics.id });
}
